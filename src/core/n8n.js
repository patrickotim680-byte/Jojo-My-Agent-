// ── n8n Engine ───────────────────────────────────────────────────────────────
//
// Feature: self-hosted n8n provisioning + real workflow build/deploy/verify.
//
// Same safety spine as deploy.js and builder.js:
//   1. PROVISION IS LOCAL AND REVERSIBLE — spins up n8n via `docker compose`
//      on this machine (or wherever this process runs). Nothing here talks
//      to a third-party cloud account. Tearing it down is `docker compose
//      down` — never destroys the volume unless explicitly asked to.
//   2. VERIFY-FIRST — a workflow is never reported "deployed and working"
//      just because the POST to /workflows returned 200. createWorkflow()
//      only creates it; verifyWorkflow() actually activates it and, if it
//      has a webhook trigger, fires a real test request and polls the
//      execution result. A workflow that was created but never verified is
//      reported as exactly that — untested — not as working.
//   3. NOTHING DESTRUCTIVE WITHOUT APPROVAL — deleting a workflow, or
//      tearing down the n8n container WITH its volume (which drops all
//      stored credentials/workflow history), requires human_approved=true,
//      same pattern as apply_deployment.
//   4. LEDGER — every provision/create/activate/verify/delete is logged to
//      memory/n8n_ledger.json so JOJO (and the human) can see what's
//      actually running and where.
//
// HONEST LIMITS:
//   - n8n has NO public API to create the first ("owner") account or to
//     mint the initial API key — that first-run step is deliberately
//     UI-only, for security, on n8n's end (not a JOJO limitation). After
//     provisioning, JOJO will print the exact one-time steps a human needs
//     to do in the browser (visit the URL, set up the owner account,
//     Settings → API → create an API key) and then wait for that key via
//     n8n_configure. Nothing past that point requires the browser again.
//   - Workflow JSON (nodes/connections) is generated by the model itself,
//     not by this module — this module's job is transport (create/get/
//     activate/delete) and verification (trigger + poll), not authoring.
//     A malformed workflow will fail at n8n's own validation and that error
//     is surfaced verbatim, not swallowed.
//   - "Verified" for a webhook-triggered workflow means: activated, a real
//     HTTP request was sent to its webhook path, and n8n's execution log
//     shows that specific execution finished with status "success" — not a
//     guarantee every branch/node in the workflow was exercised.
//   - Manually-triggered or schedule-triggered workflows can't be poked via
//     a webhook call — verifyWorkflow() falls back to confirming the
//     workflow activated cleanly and lists its trigger type, and says so
//     plainly rather than claiming an execution test that didn't happen.
//   - This assumes Docker is installed and the daemon is running. It does
//     not install Docker itself.

import { execFile } from 'child_process';
import { promisify } from 'util';
import fs from 'fs/promises';
import path from 'path';
import axios from 'axios';
import { ApprovalGate } from './approval_gate.js';
import chalk from 'chalk';

const execFileAsync = promisify(execFile);

const LEDGER_DIR  = path.join(process.cwd(), 'memory');
const LEDGER_FILE = path.join(LEDGER_DIR, 'n8n_ledger.json');
const STACK_DIR   = path.join(process.cwd(), 'hosting', 'n8n');

const PROVISION_TIMEOUT_MS = parseInt(process.env.N8N_PROVISION_TIMEOUT_MS || '120000');
const HTTP_TIMEOUT_MS      = parseInt(process.env.N8N_HTTP_TIMEOUT_MS || '20000');
const POLL_INTERVAL_MS     = 1500;
const POLL_MAX_ATTEMPTS    = 10; // ~15s of polling for an execution to land

function uid(prefix) {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
}

async function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

const COMPOSE_YML = (port) => `# Generated by JOJO (src/core/n8n.js) — self-hosted n8n
# Data (workflows, credentials, executions) persists in the named volume
# below across restarts. Nothing here talks to n8n cloud or any third party.
services:
  n8n:
    image: docker.n8n.io/n8nio/n8n:latest
    restart: unless-stopped
    ports:
      - "${port}:5678"
    environment:
      - N8N_SECURE_COOKIE=false
      - N8N_HOST=localhost
      - N8N_PORT=5678
      - WEBHOOK_URL=http://localhost:${port}/
      - GENERIC_TIMEZONE=UTC
    volumes:
      - jojo_n8n_data:/home/node/.n8n
volumes:
  jojo_n8n_data:
`;

export class N8nEngine {
  constructor() {
    // Bookkeeping only, deliberately — unlike healer/deploy/synthesis, this
    // module doesn't look a plan up by id to execute it; teardown()/
    // deleteWorkflow() are re-called directly with human_approved=true and
    // re-derive everything from their own fresh arguments. Migrating the
    // EXECUTION path to gate.apply()'s lookup-and-run pattern would mean
    // changing the tool-calling convention itself (a new apply_n8n_action
    // tool instead of re-calling n8n_teardown/n8n_delete_workflow) — a wider
    // change than this pass makes, specifically because this is destructive
    // volume/workflow deletion and that flow deserves its own full read
    // and test pass rather than a blind refactor alongside three others.
    this.gate = new ApprovalGate({ idPrefix: 'n8n', kind: 'n8n destructive action' });
    this.ledger   = { instances: [], workflows: [], events: [] };
    this.baseUrl  = process.env.N8N_BASE_URL || null;
    this.apiKey   = process.env.N8N_API_KEY  || null;
    this.port     = parseInt(process.env.N8N_PORT || '5678');
  }

  async init() {
    await fs.mkdir(LEDGER_DIR, { recursive: true });
    try {
      const raw = await fs.readFile(LEDGER_FILE, 'utf-8');
      this.ledger = { instances: [], workflows: [], events: [], ...JSON.parse(raw) };
    } catch {
      await this._saveLedger();
    }
  }

  async _saveLedger() {
    await fs.writeFile(LEDGER_FILE, JSON.stringify(this.ledger, null, 2), 'utf-8');
  }

  _log(event) {
    this.ledger.events.push({ ...event, at: new Date().toISOString() });
    this._saveLedger().catch(() => {});
  }

  _client() {
    if (!this.baseUrl) throw new Error('No n8n base URL configured. Call n8n_provision (self-host) or n8n_configure (existing instance) first.');
    if (!this.apiKey)  throw new Error('No n8n API key configured. Generate one in the n8n UI (Settings → API) and pass it to n8n_configure.');
    return axios.create({
      baseURL: `${this.baseUrl.replace(/\/$/, '')}/api/v1`,
      headers: { 'X-N8N-API-KEY': this.apiKey, 'Content-Type': 'application/json' },
      timeout: HTTP_TIMEOUT_MS,
    });
  }

  async _dockerAvailable() {
    try { await execFileAsync('docker', ['--version'], { timeout: 10_000 }); return true; }
    catch { return false; }
  }

  // ── Self-hosting ────────────────────────────────────────────────────────

  /** Writes a docker-compose.yml under hosting/n8n and brings it up. Does
   *  NOT configure an API key — that step is UI-only on n8n's end (see
   *  HONEST LIMITS). Returns exact next steps for the human. */
  async provision({ port } = {}) {
    if (!(await this._dockerAvailable())) {
      return { ok: false, error: 'Docker not found/running on this machine. Install Docker (and start the daemon) first — this module never installs Docker itself.' };
    }
    const usePort = port || this.port;
    await fs.mkdir(STACK_DIR, { recursive: true });
    const composePath = path.join(STACK_DIR, 'docker-compose.yml');
    await fs.writeFile(composePath, COMPOSE_YML(usePort), 'utf-8');

    console.log(chalk.magenta(`[n8n] docker compose up -d (port ${usePort}) in ${STACK_DIR}`));
    try {
      const res = await execFileAsync('docker', ['compose', 'up', '-d'], { cwd: STACK_DIR, timeout: PROVISION_TIMEOUT_MS });
      var stdout = `${res.stdout}\n${res.stderr}`;
    } catch (err) {
      this._log({ type: 'provision_failed', error: err.message });
      return { ok: false, error: `docker compose up failed: ${err.message}` };
    }

    const url = `http://localhost:${usePort}`;
    // Wait for the HTTP server to come up (container start != app ready).
    let healthy = false;
    for (let i = 0; i < 20; i++) {
      try { await axios.get(url, { timeout: 3000 }); healthy = true; break; }
      catch { await sleep(1500); }
    }

    this.baseUrl = url;
    const record = { id: uid('n8n_instance'), url, port: usePort, composePath, healthy, createdAt: new Date().toISOString() };
    this.ledger.instances.push(record);
    this._log({ type: 'provisioned', url, healthy });
    await this._saveLedger();

    return {
      ok: true,
      url,
      healthy,
      composePath,
      nextSteps: [
        `1. Open ${url} in a browser and create the owner account (one-time — n8n has no API for this step, by design).`,
        `2. In the n8n UI: Settings → n8n API → Create an API key, and copy it.`,
        `3. Call n8n_configure with base_url="${url}" and the API key. After that, no browser step is needed again.`,
      ],
      note: healthy
        ? 'Container is up and responding.'
        : 'Container started but did not respond to an HTTP check within ~30s — give it a bit longer, then check `docker compose logs` in ' + STACK_DIR + '.',
    };
  }

  /** Point JOJO at an already-existing n8n instance (self-hosted elsewhere,
   *  or one just provisioned) once the human has an API key. */
  async configure({ baseUrl, apiKey }) {
    if (!baseUrl || !apiKey) return { ok: false, error: 'Both base_url and api_key are required.' };
    this.baseUrl = baseUrl;
    this.apiKey  = apiKey;
    try {
      const client = this._client();
      const res = await client.get('/workflows', { params: { limit: 1 } });
      this._log({ type: 'configured', baseUrl });
      return { ok: true, message: `Connected to ${baseUrl} — API key verified (${res.data?.data?.length ?? 0} workflow(s) visible).` };
    } catch (err) {
      const detail = err.response ? `${err.response.status} ${JSON.stringify(err.response.data)}` : err.message;
      return { ok: false, error: `Could not verify connection: ${detail}` };
    }
  }

  /** Tears down the container. destroyVolume=true (irreversible — drops all
   *  workflows/credentials/history) requires human_approved=true. */
  async teardown({ destroyVolume = false, humanApproved = false } = {}) {
    if (destroyVolume && !humanApproved) {
      const planId = uid('n8n_teardown');
      this.gate.propose({ id: planId, type: 'teardown_volume' });
      return { ok: false, pending: true, planId, summary: `Tearing down WITH volume deletion drops all workflows/credentials/history in ${STACK_DIR}. This is irreversible. Call n8n_teardown again with human_approved=true to proceed, or without destroy_volume to just stop the container.` };
    }
    const args = ['compose', 'down', ...(destroyVolume ? ['-v'] : [])];
    try {
      const res = await execFileAsync('docker', args, { cwd: STACK_DIR, timeout: PROVISION_TIMEOUT_MS });
      this._log({ type: 'teardown', destroyVolume });
      if (destroyVolume) this._clearPendingByType('teardown_volume'); // pre-existing gap, fixed in passing:
        // the approved re-call never cleared the pending record its own first
        // (unapproved) call created, so it lingered in listPending()/
        // getContext() forever even after the real teardown succeeded
      return { ok: true, output: `${res.stdout}\n${res.stderr}` };
    } catch (err) {
      return { ok: false, error: err.message };
    }
  }

  // ── Workflow CRUD ───────────────────────────────────────────────────────

  /** workflow must be a valid n8n workflow object: { name, nodes, connections,
   *  settings? }. Created INACTIVE — call verifyWorkflow to activate + test. */
  async createWorkflow(workflow) {
    if (!workflow || !Array.isArray(workflow.nodes) || !workflow.connections) {
      return { ok: false, error: 'workflow must include at minimum { name, nodes: [...], connections: {...} }.' };
    }
    try {
      const client = this._client();
      const res = await client.post('/workflows', {
        name: workflow.name || 'Untitled (JOJO)',
        nodes: workflow.nodes,
        connections: workflow.connections,
        settings: workflow.settings || {},
      });
      const created = res.data;
      this.ledger.workflows.push({ id: created.id, name: created.name, active: false, verified: false, createdAt: new Date().toISOString() });
      this._log({ type: 'workflow_created', id: created.id, name: created.name });
      await this._saveLedger();
      return { ok: true, id: created.id, name: created.name, active: !!created.active };
    } catch (err) {
      const detail = err.response ? `${err.response.status} ${JSON.stringify(err.response.data)}` : err.message;
      return { ok: false, error: `n8n rejected the workflow: ${detail}` };
    }
  }

  async listWorkflows() {
    try {
      const client = this._client();
      const res = await client.get('/workflows');
      return { ok: true, workflows: (res.data?.data || []).map(w => ({ id: w.id, name: w.name, active: w.active })) };
    } catch (err) {
      return { ok: false, error: err.response ? `${err.response.status} ${JSON.stringify(err.response.data)}` : err.message };
    }
  }

  _webhookTrigger(workflowNodes) {
    return (workflowNodes || []).find(n => n.type === 'n8n-nodes-base.webhook');
  }

  /** Activates the workflow, and — if it has a webhook trigger — fires a
   *  real test request at it and polls /executions for the result. Never
   *  reports success without having actually observed one. */
  async verifyWorkflow(workflowId, { testPayload = {} } = {}) {
    const client = this._client();

    let wf;
    try {
      wf = (await client.get(`/workflows/${workflowId}`)).data;
    } catch (err) {
      return { ok: false, error: `Could not fetch workflow ${workflowId}: ${err.response ? err.response.status : err.message}` };
    }

    try {
      await client.post(`/workflows/${workflowId}/activate`);
    } catch (err) {
      const detail = err.response ? `${err.response.status} ${JSON.stringify(err.response.data)}` : err.message;
      this._log({ type: 'activate_failed', id: workflowId, error: detail });
      return { ok: false, error: `Activation failed: ${detail}` };
    }

    const webhookNode = this._webhookTrigger(wf.nodes);
    if (!webhookNode) {
      const triggerTypes = (wf.nodes || []).filter(n => /trigger|webhook|cron|schedule/i.test(n.type)).map(n => n.type);
      this._log({ type: 'activated_no_webhook_test', id: workflowId, triggerTypes });
      this._markVerified(workflowId, false);
      return {
        ok: true,
        activated: true,
        executionTested: false,
        note: `Activated successfully. Trigger type(s): ${triggerTypes.join(', ') || 'unknown'} — not webhook-triggered, so no live execution test was run (see honest limits). Trust "activated," not "tested end to end."`,
      };
    }

    const webhookPath = webhookNode.parameters?.path;
    const method = (webhookNode.parameters?.httpMethod || 'GET').toUpperCase();
    if (!webhookPath) {
      this._markVerified(workflowId, false);
      return { ok: true, activated: true, executionTested: false, note: 'Activated, but the webhook node has no path configured to test against.' };
    }

    const webhookUrl = `${this.baseUrl.replace(/\/$/, '')}/webhook/${webhookPath.replace(/^\//, '')}`;
    let triggerOk = true;
    try {
      if (method === 'GET') await axios.get(webhookUrl, { timeout: HTTP_TIMEOUT_MS, params: testPayload });
      else await axios({ method: method.toLowerCase(), url: webhookUrl, data: testPayload, timeout: HTTP_TIMEOUT_MS });
    } catch (err) {
      // A webhook can still 4xx/5xx at the HTTP layer while n8n logs the
      // execution — don't bail yet, go check the execution log itself.
      triggerOk = err.response ? true : false;
    }

    // Poll for the execution this trigger produced.
    let execution = null;
    for (let i = 0; i < POLL_MAX_ATTEMPTS; i++) {
      await sleep(POLL_INTERVAL_MS);
      try {
        const res = await client.get('/executions', { params: { workflowId, limit: 1 } });
        const latest = res.data?.data?.[0];
        if (latest) { execution = latest; break; }
      } catch { /* keep polling */ }
    }

    if (!execution) {
      this._markVerified(workflowId, false);
      return { ok: false, activated: true, executionTested: true, error: 'Webhook request was sent but no execution appeared in /executions within the poll window — n8n may not have received it (check WEBHOOK_URL / port mapping), or it is still queued.' };
    }

    const success = execution.finished === true && execution.status !== 'error' && !execution.stoppedAt !== undefined ? execution.status !== 'error' : execution.finished === true;
    this._markVerified(workflowId, success);
    this._log({ type: 'verified', id: workflowId, executionId: execution.id, success });
    return {
      ok: success,
      activated: true,
      executionTested: true,
      executionId: execution.id,
      status: execution.status || (execution.finished ? 'success' : 'unknown'),
      note: success
        ? 'Activated, live webhook request sent, and n8n execution log confirms it completed successfully.'
        : `Activated and a request was sent, but the resulting execution did not report success (status: ${execution.status || 'unknown'}). Check /executions/${execution.id} in the n8n UI for the failing node.`,
    };
  }

  _markVerified(id, verified) {
    const rec = this.ledger.workflows.find(w => w.id === id);
    if (rec) { rec.verified = verified; rec.active = true; rec.verifiedAt = new Date().toISOString(); }
    this._saveLedger().catch(() => {});
  }

  /** Import a workflow JSON pulled from a link (e.g. a shared n8n workflow
   *  export or gist) — this function does NOT fetch the URL itself (use
   *  web_fetch for that, same separation-of-concerns as everywhere else in
   *  the codebase); it takes the already-fetched JSON and validates +
   *  creates it, then hands back to the caller to run verifyWorkflow. */
  async importWorkflowJson(rawJsonOrObject) {
    let obj = rawJsonOrObject;
    if (typeof obj === 'string') {
      try { obj = JSON.parse(obj); }
      catch (err) { return { ok: false, error: `Not valid JSON: ${err.message}` }; }
    }
    if (!obj.nodes || !obj.connections) {
      return { ok: false, error: 'That JSON does not look like an n8n workflow export — missing nodes/connections.' };
    }
    return this.createWorkflow(obj);
  }

  async deleteWorkflow(workflowId, humanApproved = false) {
    if (!humanApproved) {
      const planId = uid('n8n_delete');
      this.gate.propose({ id: planId, type: 'delete_workflow', workflowId });
      return { ok: false, pending: true, planId, summary: `Deleting workflow ${workflowId} is irreversible. Call again with human_approved=true to proceed.` };
    }
    try {
      const client = this._client();
      await client.delete(`/workflows/${workflowId}`);
      this.ledger.workflows = this.ledger.workflows.filter(w => w.id !== workflowId);
      this._log({ type: 'workflow_deleted', id: workflowId });
      this._clearPendingByType('delete_workflow', workflowId); // same pre-existing gap, same fix
      await this._saveLedger();
      return { ok: true };
    } catch (err) {
      return { ok: false, error: err.response ? `${err.response.status} ${JSON.stringify(err.response.data)}` : err.message };
    }
  }

  /** Best-effort cleanup for the "re-call the same method with
   *  human_approved=true" pattern this module uses instead of gate.apply()'s
   *  lookup-by-id — see the constructor comment for why. Purges any pending
   *  record matching this type (+ workflowId if given) now that the real
   *  action actually happened, so it stops showing as "awaiting approval". */
  _clearPendingByType(type, workflowId) {
    for (const record of this.gate.list()) {
      if (record.type === type && (workflowId === undefined || record.workflowId === workflowId)) {
        this.gate.dismiss(record.id).catch(() => {});
      }
    }
  }

  /** Every pending destructive action (delete_workflow, teardown_volume)
   *  currently awaiting human_approved=true. */
  listPending() {
    return this.gate.list();
  }

  /** Discard a pending destructive action without executing it. */
  async dismissAction(planId) {
    if (!this.gate.get(planId)) return { ok: false, error: `No pending n8n action with id "${planId}".` };
    await this.gate.dismiss(planId);
    return { ok: true, message: `Discarded pending action ${planId}. Nothing was changed.` };
  }

  getContext() {
    const inst = this.ledger.instances.at(-1);
    const wfLines = this.ledger.workflows.slice(-5).map(w =>
      `  [${w.id}] ${w.name} — ${w.verified ? 'verified ✓' : w.active ? 'active, unverified' : 'created, inactive'}`);
    const pendingLines = this.listPending().map(p =>
      `  [${p.id}] ${p.type}${p.workflowId ? ` (${p.workflowId})` : ''} — awaiting approval`);
    return [
      inst ? `Self-hosted n8n instance: ${inst.url} (last provisioned ${inst.createdAt})` : (this.baseUrl ? `Configured n8n instance: ${this.baseUrl}` : 'No n8n instance provisioned/configured yet.'),
      wfLines.length ? `Recent workflows:\n${wfLines.join('\n')}` : 'No workflows created yet.',
      pendingLines.length ? `Pending destructive actions (need approval):\n${pendingLines.join('\n')}` : 'No pending destructive actions.',
    ].join('\n');
  }
}

